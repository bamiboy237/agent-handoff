import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

const CONFIG_FILE = ".handoff.json";

// Shipped next to dist/, uploaded to every sandbox, and part of the cache key.
export const RUNNER_SCRIPT = new URL("../remote/runner.sh", import.meta.url);
export const WATCH_SCRIPT = new URL("../remote/watch.mjs", import.meta.url);
export const WATCH_PAGE_SCRIPT = new URL("../remote/watch-page.mjs", import.meta.url);
export const TRANSCRIPT_SCRIPT = new URL("../remote/transcript.mjs", import.meta.url);

interface Detector {
  lockfiles: string[];
  command: string;
}

// Within a group only the first matching lockfile applies, so a repository
// with both package-lock.json and pnpm-lock.yaml installs once.
const DETECTOR_GROUPS: Detector[][] = [
  [
    { lockfiles: ["pnpm-lock.yaml"], command: "npx --yes pnpm install --frozen-lockfile" },
    { lockfiles: ["yarn.lock"], command: "npx --yes yarn install --frozen-lockfile" },
    { lockfiles: ["bun.lock", "bun.lockb"], command: "npx --yes bun install --frozen-lockfile" },
    { lockfiles: ["package-lock.json"], command: "npm ci" },
  ],
  [
    {
      lockfiles: ["uv.lock"],
      command: "command -v uv >/dev/null || curl -LsSf https://astral.sh/uv/install.sh | sh\nuv sync --frozen",
    },
    { lockfiles: ["poetry.lock"], command: "pip install --user poetry\npoetry install --no-interaction" },
    { lockfiles: ["requirements.txt"], command: "pip install -r requirements.txt" },
  ],
  [
    {
      lockfiles: ["Cargo.lock"],
      command: "command -v cargo >/dev/null || curl -sSf https://sh.rustup.rs | sh -s -- -y\ncargo fetch --locked",
    },
  ],
  [{ lockfiles: ["go.sum"], command: "require_tool go\ngo mod download" }],
  [{ lockfiles: ["Gemfile.lock"], command: "require_tool bundle\nbundle install" }],
];

export interface SetupPlan {
  detected: string[];
  commands: string[];
  cacheKey: string;
}

function readHandoffConfig(root: string): string[] {
  const path = join(root, CONFIG_FILE);
  if (!existsSync(path)) return [];
  let config: unknown;
  try {
    config = JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    throw new Error(`${CONFIG_FILE} is not valid JSON.`, { cause: error });
  }
  const setup = (config as { setup?: unknown }).setup ?? [];
  if (!Array.isArray(setup) || !setup.every((step) => typeof step === "string")) {
    throw new Error(`${CONFIG_FILE} "setup" must be an array of shell commands.`);
  }
  return setup;
}

// cacheInputs are extra values that invalidate the cached sandbox snapshot,
// such as the agent version and the runner script.
export function planSetup(root: string, cacheInputs: string[]): SetupPlan {
  const hash = createHash("sha256");
  for (const input of cacheInputs) hash.update(input).update("\0");

  const detected: string[] = [];
  const commands: string[] = [];
  for (const group of DETECTOR_GROUPS) {
    for (const detector of group) {
      const lockfile = detector.lockfiles.find((name) => existsSync(join(root, name)));
      if (!lockfile) continue;
      detected.push(lockfile);
      commands.push(detector.command);
      hash.update(lockfile).update("\0").update(readFileSync(join(root, lockfile))).update("\0");
      break;
    }
  }

  const extra = readHandoffConfig(root);
  if (extra.length > 0) detected.push(CONFIG_FILE);
  commands.push(...extra);
  hash.update(JSON.stringify(extra));

  return { detected, commands, cacheKey: hash.digest("hex") };
}

export function renderSetupScript(commands: string[]): string {
  const steps = commands.map((command) => `echo ${JSON.stringify(`+ ${command}`)}\n${command}`);
  return [
    "#!/usr/bin/env bash",
    "# Generated by agent-handoff from the project's lockfiles and .handoff.json.",
    "set -euo pipefail",
    'export PATH="$HOME/.local/bin:$HOME/.cargo/bin:$PATH"',
    'require_tool() { command -v "$1" >/dev/null || { echo "$1 is not installed in the sandbox. Add an install step to .handoff.json." >&2; exit 1; }; }',
    'cd "$1"',
    ...steps,
    "",
  ].join("\n");
}
